/**
 * Where bar 40's downbeat sits — the D-major chord that ends the show and the
 * moment the roll's finale card is meant to lock up.
 *
 * The standalone deliverable pins the roll's duration to this and lets the
 * crawl speed float, so a longer contributor list runs faster rather than
 * running past the music. The in-app roll does not do that yet (credits.tsx
 * runs a fixed 40 px/s crawl and lets its duration float with content), so the
 * landmark is exported for it to adopt rather than assumed.
 */
export const CREDITS_THEME_BELL_SECONDS = CREDITS_FINAL_STEP * CREDITS_STEP_SECONDS

/** Music plus the final chord's ring-out. */
export const CREDITS_THEME_DURATION = CREDITS_DURATION

function creditsSmoothstep(t: number): number {
  return t * t * (3 - 2 * t)
}

function creditsDynamics(bar: number): number {
  if (bar <= CREDITS_DYNAMICS[0][0]) return CREDITS_DYNAMICS[0][1]
  for (let index = 1; index < CREDITS_DYNAMICS.length; index += 1) {
    const [barB, levelB] = CREDITS_DYNAMICS[index]
    if (bar <= barB) {
      const [barA, levelA] = CREDITS_DYNAMICS[index - 1]
      const span = barB - barA
      const t = span <= 0 ? 1 : creditsSmoothstep((bar - barA) / span)
      return levelA + (levelB - levelA) * t
    }
  }
  return CREDITS_DYNAMICS[CREDITS_DYNAMICS.length - 1][1]
}

function creditsSectionForBar(bar: number): CreditsSection {
  let found = CREDITS_SECTIONS[0]
  for (const section of CREDITS_SECTIONS) {
    if (bar >= section.startBar) found = section
  }
  return found
}

/**
 * Flatten one pitched channel into events, truncating every note at the next
 * onset in the SAME channel. An APU channel register write retriggers rather
 * than layering, so this is both authentic and what guarantees the four-voice
 * ceiling: four monophonic channels can never sound five things.
 */
function creditsPitchedEvents(
  steps: readonly CreditsNoteStep[],
  channel: CreditsPitchedChannel,
): CreditsEvent[] {
  const onsets: number[] = []
  for (let step = 0; step < steps.length; step += 1) {
    if (steps[step] !== null && steps[step] !== undefined) onsets.push(step)
  }
  return onsets.map((step, index) => {
    const bar = step / CREDITS_STEPS_PER_BAR
    const voice = creditsSectionForBar(Math.floor(bar))[channel]
    const next = onsets[index + 1]
    const untilNext = next === undefined
      ? Number.POSITIVE_INFINITY
      : (next - step) * CREDITS_STEP_SECONDS
    const duration = step === CREDITS_FINAL_STEP
      ? CREDITS_DURATION - step * CREDITS_STEP_SECONDS
      : Math.min(voice.gate * CREDITS_STEP_SECONDS, untilNext)
    return {
      channel,
      kind: 'note' as const,
      time: step * CREDITS_STEP_SECONDS,
      duration,
      gain: voice.volume
        * CREDITS_ACCENTS[step % CREDITS_STEPS_PER_BAR]
        * creditsDynamics(bar),
      frequency: steps[step] as number,
      duty: voice.duty,
      attack: voice.attack,
      sustain: voice.sustain,
    }
  })
}

function creditsNoiseEvents(steps: readonly CreditsDrumStep[]): CreditsEvent[] {
  const events: CreditsEvent[] = []
  for (let step = 0; step < steps.length; step += 1) {
    const token = steps[step]
    if (!token) continue
    const drum = CREDITS_DRUMS[token]
    const bar = step / CREDITS_STEPS_PER_BAR
    let next = step + 1
    while (next < steps.length && !steps[next]) next += 1
    const untilNext = next >= steps.length
      ? Number.POSITIVE_INFINITY
      : (next - step) * CREDITS_STEP_SECONDS
    events.push({
      channel: 'noise',
      kind: 'noise',
      time: step * CREDITS_STEP_SECONDS,
      duration: Math.min(drum.decay, untilNext),
      gain: drum.volume * Math.min(1.12, creditsDynamics(bar)),
      period: drum.period,
      rateFrom: drum.rateFrom,
    })
  }
  return events
}

let cached: CreditsPlan | null = null

/**
 * The whole cue as one event list.
 *
 * It is through-composed and ENDS: everything goes in introEvents and
 * loopEvents is empty, which is how the shared runtime is told a cue plays
 * once. Built on first call and reused, since the plan is a pure function of
 * the score.
 */
export function creditsCuePlan(): CreditsPlan {
  if (cached) return cached
  const events: readonly CreditsEvent[] = [
    ...creditsPitchedEvents(CREDITS_PULSE_1, 'pulse1'),
    ...creditsPitchedEvents(CREDITS_PULSE_2, 'pulse2'),
    ...creditsPitchedEvents(CREDITS_TRIANGLE, 'triangle'),
    ...creditsNoiseEvents(CREDITS_NOISE),
  ].sort((a, b) => a.time - b.time)
  cached = {
    introDuration: CREDITS_DURATION,
    loopDuration: 0,
    introEvents: events,
    loopEvents: [],
    bellTime: CREDITS_THEME_BELL_SECONDS,
  }
  return cached
}
