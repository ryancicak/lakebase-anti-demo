/**
 * THE LONG WALK BACK — the end-title cue, ported from the standalone credits
 * deliverable that the user heard and approved.
 *
 * The score is unchanged: 40 bars of 4/4 at 110 BPM, 87.27 s of music plus a
 * 0.45 s ring-out. Two pulse voices switching between 12.5% / 25% / 50% duty,
 * one triangle on the bass, one noise channel carrying every drum as a real
 * 15-bit LFSR at a different timer period. Never more than four voices sound
 * at once, and nothing here is a sine, a sawtooth or a filter.
 *
 * D minor -> B-flat major -> F major -> D MAJOR -> one bar of D minor -> D
 * major. Bars 29-36 are the payoff: FINAL BELL's D-A-C-F hook, four sixteenths
 * in the title theme, returns as half notes across two bars and translated
 * into the parallel major as D-A-C#-F#, sustained on pulse 1 while pulse 2
 * climbs above it. Bar 39 quotes the title theme's closing D-major arpeggio;
 * bar 40 lands the chord.
 *
 * WHAT CHANGED IN THE PORT, and nothing else did:
 *   - The cue is planned into the flat CueEvent list that audio.ts's shared
 *     runtime already plays for the title score and the six round cues, rather
 *     than carrying its own scheduler, its own PeriodicWave cache and its own
 *     LFSR. Three schedulers became one.
 *   - The note tail is the runtime's: a 3.5 ms linear ramp to zero off a -16 dB
 *     shelf, instead of an exponential run to -80 dB across the back of the
 *     gate. Same lengths, same onsets, no hole in front of the bar line.
 *   - Bar 40's bell is a LANDMARK, not an event. The roll strikes the bell
 *     itself (credits.tsx), so the cue exposes CREDITS_THEME_BELL_SECONDS and
 *     leaves the noise channel empty under it rather than striking a second
 *     one. Two bells 14 s apart would be worse than one in the right place.
 *
 * Generated by lakebase-anti-demo-scratch/credits/audio/integration/generate.mjs.
 * The score data below is byte-identical to credits-theme.audio.ts; edit the
 * scratch arrangement and regenerate rather than editing this file.
 */

export type CreditsChannel = 'pulse1' | 'pulse2' | 'triangle' | 'noise'

/** The shape audio.ts's cue runtime consumes. Structural, not imported. */
export interface CreditsEvent {
  readonly channel: CreditsChannel
  readonly kind: 'note' | 'noise'
  readonly time: number
  readonly duration: number
  readonly gain: number
  readonly frequency?: number
  readonly duty?: number
  readonly attack?: number
  readonly sustain?: number
  readonly period?: number
  readonly rateFrom?: number
}

export interface CreditsPlan {
  readonly introDuration: number
  readonly loopDuration: number
  readonly introEvents: readonly CreditsEvent[]
  readonly loopEvents: readonly CreditsEvent[]
  /** Seconds from the cue's first beat to bar 40's downbeat. */
  readonly bellTime: number
}

/**
 * Chosen to sit AT the title score, not at the rounds.
 *
 * The rounds are at 0.1 because somebody is talking over them. Nobody talks
 * over the credits: like the title screen it plays to a room that is watching,
 * so it belongs at the title screen's level rather than under it.
 *
 * The number is SMALLER than the title's 0.18 because the cue is denser: 1091
 * events over 88 s against the title score's 944 over 77 s, and where the
 * title loop holds one steady weight this one is written to swell. Measured
 * off the live graph over both whole forms, the standalone's 0.22 ran 4.1 dB
 * hot against the title score. 0.14 matches it. Opening the roll from the
 * title screen is then not a level change, and the piece's own dynamic curve
 * still does what it was written to do: half-lit at bar 1, biggest at bar 40.
 */
